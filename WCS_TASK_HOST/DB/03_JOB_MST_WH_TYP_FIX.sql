-- =====================================================================
--  JOB_MST.WH_TYP 정정  ('A' -> '10')   (PostgreSQL)
--
--  왜 필요한가
--    HOST 태스크는 모든 조회에 WH_TYP 조건을 붙인다.
--      WHERE WH_TYP = :WH_TYP        -- ini 의 [DB] WH_TYP, 기본 '10'
--    그런데 JOB_MST 만 WH_TYP 가 'A' 로 들어가 있어서
--    작업지시(O) / 완료보고(F) / 미실행작업 조회가 전부 0건이 된다.
--    즉 HOST 를 KET_WCS 에 붙여도 작업 관련 동작이 하나도 일어나지 않는다.
--
--  'A' 가 오타라고 보는 근거
--    1. 같은 테이블의 이력인 JOB_MST_HIS 는 13,200 건 전부 WH_TYP = '10'
--    2. DB 전체에서 WH_TYP = 'A' 인 테이블은 JOB_MST 하나뿐
--       (CV_DATA / SC_DATA / EQP_MST / CELL_MST / IF_* 전부 '10')
--    3. 다른 태스크의 WCS_DB.INI 도 WH_TYP=10
--    4. 문제의 508 건은 2026-07-10 15:34:23 ~ 15:34:36, 13초 만에
--       일괄 적재된 흔적이라 초기 이관 시 값이 잘못 들어간 것으로 보인다
--
--  실행 : psql -h 127.0.0.1 -p 5432 -U KET_WCS -d KET_WCS -f 03_JOB_MST_WH_TYP_FIX.sql
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1) 되돌릴 수 있도록 대상 키를 먼저 남긴다
--    (되돌리기는 맨 아래 주석 블록 참고)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS JOB_MST_WHTYP_FIX_BAK AS
SELECT LUGG_NO, WH_TYP AS OLD_WH_TYP, NOW() AS BAK_DT
  FROM JOB_MST
 WHERE WH_TYP = 'A';

-- ---------------------------------------------------------------------
-- 2) 정정
-- ---------------------------------------------------------------------
UPDATE JOB_MST
   SET WH_TYP = '10'
 WHERE WH_TYP = 'A';

COMMIT;


